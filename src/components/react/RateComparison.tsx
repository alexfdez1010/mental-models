import { useId, useState } from 'react';
import { cx } from '@/components/react/cx';

/** One group's event count and its denominator in a scenario. */
export interface RateComparisonGroup {
  /** Visible group name; author it in the lesson's language. */
  label: string;
  /** Number of events, an integer between zero and total. */
  events: number;
  /** Positive integer count of eligible observations. */
  total: number;
}

/** Authored observations for one period or condition, without causal interpretation. */
export interface RateComparisonScenario {
  /** Visible scenario name, also used in the native selector. */
  label: string;
  /** At least two groups; the contrast subtracts the second rate from the first. */
  groups: RateComparisonGroup[];
}

/** Props for a shared-scale chart of observed rates. */
export interface RateComparisonProps {
  /** Nonempty authored scenarios; no observations are generated by the component. */
  scenarios: RateComparisonScenario[];
  /** Number formatting and default control labels. */
  locale?: 'en' | 'es';
  /** Optional figure caption. */
  title?: string;
  /** Label for the scenario selector. */
  scenarioLabel?: string;
  /** Accessible label identifying the visible event/total fraction. */
  countsLabel?: string;
  /** Label preceding the named first-minus-second contrast. */
  differenceLabel?: string;
  /** Singular percentage-point unit. */
  pointLabel?: string;
  /** Plural percentage-point unit. */
  pointsLabel?: string;
  /** Additional classes merged with the figure's layout. */
  className?: string;
}

function validateScenarios(scenarios: RateComparisonScenario[]): void {
  if (!Array.isArray(scenarios) || scenarios.length === 0) {
    throw new Error('RateComparison: `scenarios` must contain at least one scenario.');
  }
  for (const [scenarioIndex, scenario] of scenarios.entries()) {
    const path = `RateComparison: scenarios[${scenarioIndex}]`;
    if (!scenario || typeof scenario.label !== 'string' || !scenario.label.trim()) {
      throw new Error(`${path}.label must be nonempty.`);
    }
    if (!Array.isArray(scenario.groups) || scenario.groups.length < 2) {
      throw new Error(`${path}.groups must contain at least two groups.`);
    }
    for (const [groupIndex, group] of scenario.groups.entries()) {
      const groupPath = `${path}.groups[${groupIndex}]`;
      if (!group || typeof group.label !== 'string' || !group.label.trim()) {
        throw new Error(`${groupPath}.label must be nonempty.`);
      }
      if (!Number.isSafeInteger(group.total) || group.total <= 0) {
        throw new Error(`${groupPath}.total must be a positive safe integer.`);
      }
      if (!Number.isSafeInteger(group.events) || group.events < 0 || group.events > group.total) {
        throw new Error(`${groupPath}.events must be a safe integer between zero and total.`);
      }
    }
  }
}

/**
 * Compare authored event rates on a common zero-to-one bar scale.
 * Counts and rates remain readable without motion; changing the scenario uses
 * a labelled native select and announces the updated observations and contrast.
 */
export function RateComparison({
  scenarios,
  locale = 'en',
  title,
  scenarioLabel,
  countsLabel,
  differenceLabel,
  pointLabel,
  pointsLabel,
  className,
}: RateComparisonProps) {
  // Validate every authored scenario before hooks, including initially hidden data.
  validateScenarios(scenarios);
  for (const [name, label] of Object.entries({ scenarioLabel, countsLabel, differenceLabel, pointLabel, pointsLabel })) {
    if (label !== undefined && (typeof label !== 'string' || !label.trim())) {
      throw new Error(`RateComparison: ${name} must be nonempty when provided.`);
    }
  }

  const id = useId();
  const [scenarioIndex, setScenarioIndex] = useState(0);
  const activeIndex = Math.min(scenarioIndex, scenarios.length - 1);
  const scenario = scenarios[activeIndex]!;
  const first = scenario.groups[0]!;
  const second = scenario.groups[1]!;
  const spanish = locale === 'es';
  const numberLocale = spanish ? 'es-ES' : 'en-US';
  const counts = new Intl.NumberFormat(numberLocale);
  const percent = new Intl.NumberFormat(numberLocale, { style: 'percent', maximumFractionDigits: 2 });
  const signed = new Intl.NumberFormat(numberLocale, { maximumFractionDigits: 2, signDisplay: 'exceptZero' });
  const difference = (first.events / first.total - second.events / second.total) * 100;
  const singular = new Intl.PluralRules(numberLocale, { maximumFractionDigits: 2 }).select(Math.abs(difference)) === 'one';
  const unit = singular
    ? pointLabel ?? (spanish ? 'punto porcentual' : 'percentage point')
    : pointsLabel ?? (spanish ? 'puntos porcentuales' : 'percentage points');

  return (
    <figure className={cx('not-prose my-8', className)} aria-labelledby={title ? `${id}-title` : undefined}>
      {title ? (
        <figcaption id={`${id}-title`} className="mb-4 font-display text-lg font-semibold text-ink-900">
          {title}
        </figcaption>
      ) : null}

      {scenarios.length > 1 ? (
        <div className="mb-5">
          <label htmlFor={`${id}-scenario`} className="block text-sm font-semibold text-ink-700">
            {scenarioLabel ?? (spanish ? 'Escenario' : 'Scenario')}
          </label>
          <select
            id={`${id}-scenario`}
            value={activeIndex}
            onChange={(event) => setScenarioIndex(Number(event.currentTarget.value))}
            className="mt-2 min-h-11 w-full max-w-full rounded-card border border-ink-300 bg-surface px-3 py-2 text-sm text-ink-900 focus-visible:outline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-brand-700"
          >
            {scenarios.map((item, index) => <option key={index} value={index}>{item.label}</option>)}
          </select>
        </div>
      ) : (
        <p className="mb-4 text-sm font-semibold text-ink-700">{scenario.label}</p>
      )}

      <div aria-live="polite" aria-atomic="true">
        <ul role="list" className="space-y-5">
          {scenario.groups.map((group, index) => (
            <li key={index}>
              <div className="mb-2 flex flex-wrap items-baseline justify-between gap-x-4 gap-y-1">
                <span className="min-w-0 break-words text-sm font-medium text-ink-900">{group.label}</span>
                <span className="flex flex-wrap items-baseline gap-x-4 gap-y-1 font-mono text-sm tabular-nums text-ink-700">
                  <span>
                    <span className="sr-only">{countsLabel ?? (spanish ? 'Casos del total' : 'Events out of total')}: </span>
                    {counts.format(group.events)} / {counts.format(group.total)}
                  </span>
                  <strong className="font-semibold text-ink-900">{percent.format(group.events / group.total)}</strong>
                </span>
              </div>
              <div aria-hidden="true" className="h-3 overflow-hidden rounded-pill bg-ink-100 ring-1 ring-ink-500">
                <div
                  className="h-full w-full origin-left bg-brand-700 transition-transform duration-300 motion-reduce:transition-none"
                  style={{ transform: `scaleX(${group.events / group.total})` }}
                />
              </div>
            </li>
          ))}
        </ul>
        <div aria-hidden="true" className="mt-2 flex justify-between font-mono text-xs tabular-nums text-ink-600">
          <span>{percent.format(0)}</span>
          <span>{percent.format(1)}</span>
        </div>

        <dl className="mt-5">
          <dt className="break-words text-sm text-ink-700">
            {differenceLabel ?? (spanish ? 'Diferencia' : 'Difference')}: {first.label} − {second.label}
          </dt>
          <dd className="mt-1 font-mono text-base font-semibold tabular-nums text-ink-900">
            {signed.format(difference)} {unit}
          </dd>
        </dl>
      </div>
    </figure>
  );
}

export default RateComparison;
