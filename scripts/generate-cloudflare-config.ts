/** Generate Cloudflare Pages HTTP redirects from the shared learning-path tags. */
import { writeFileSync } from 'node:fs';
import { roadmapTags } from '../src/lib/roadmap-meta';

const redirects = roadmapTags.flatMap((tag) => [
  `/roadmap/${tag} /catalog?tag=${tag} 301`,
  `/es/roadmap/${tag} /es/catalog?tag=${tag} 301`,
]);

writeFileSync(
  new URL('../public/_redirects', import.meta.url),
  ['# Generated by scripts/generate-cloudflare-config.ts; edit roadmapTags instead.', ...redirects, ''].join('\n'),
);
console.log(`Generated ${redirects.length} Cloudflare Pages redirects.`);
